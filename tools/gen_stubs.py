#!/usr/bin/env python3
"""Generate aborting stubs for decomp functions with no C on the host yet.

Writes <unit>.stubs.inc (wrapper units) or <unit>.stubs.c (standalone units)
under --out. Prototypes: the one visible in the unit's TU, else include/, else
the most common one elsewhere with types erased; none at all gives
`static void f(void)`.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import nwunits  # noqa: E402

PRAGMA_PUSH = ("#pragma GCC diagnostic push\n"
               '#pragma GCC diagnostic ignored "-Wunused-parameter"\n')
PRAGMA_POP = "#pragma GCC diagnostic pop\n"


def _origin(f: nwunits.Function) -> str:
    if f.erased:
        return f"prototype from {f.origin}, types erased"
    if f.origin.startswith(("unresolved", "no declaration")):
        return f.origin
    return f"prototype from {f.origin}"


def why(f: nwunits.Function) -> str:
    """The reason a stub hit prints."""
    treatment = f.unit.treatment
    if treatment in ("editor", "dead"):
        return f"{treatment} unit"
    if f.overridden:
        return "override without a port body"
    if treatment == "compile":
        return "no C in the decomp yet"
    return f"{treatment} unit without a port body"


def stub_text(f: nwunits.Function) -> str:
    p = f.proto
    params = nwunits.definition_params(p.params) if p.prototyped else "void"
    storage = "static " if f.static else ""
    lines = [f"/* 0x{f.address:08x} {f.name}: {_origin(f)} */",
             storage + nwunits.head(p.ret, f.host, params),
             "{",
             f'    NW_STUB("{f.unit.name}", "{f.name}", 0x{f.address:08x}u, "{why(f)}");']
    if p.ret != "void":
        lines.append(f"    return ({p.ret}){{0}};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def declaration_text(f: nwunits.Function) -> str:
    p = f.proto
    params = p.params if p.prototyped else ""
    return nwunits.head(p.ret, f.host, params) + ";"


def render(unit: nwunits.Unit) -> str:
    stubs = [f for f in unit.functions if f.provider == "stub"]
    ports = [f for f in unit.functions if f.provider == "port"]
    out = [f"/* Generated by tools/gen_stubs.py for decomp unit {unit.name} "
           f"({unit.treatment}); do not edit. */\n"]
    if unit.kind == "standalone":
        out.append("#include <stddef.h>\n#include <stdint.h>\n\n#include \"nu_types.h\"\n")
        for header in sorted({f.include for f in stubs + ports if f.include}):
            out.append(f'#include "{header}"\n')
    out.append('#include "port/stub.h"\n')
    if ports:
        out.append("\n/* Defined by the port. */\n")
        out.extend(declaration_text(f) + "\n" for f in ports)
    if stubs:
        out.append("\n" + PRAGMA_PUSH)
        for f in stubs:
            out.append("\n" + stub_text(f))
        out.append("\n" + PRAGMA_POP)
    if unit.kind == "standalone":
        out.append(f'\n#include "{unit.name.rsplit("/", 1)[-1]}.funcmap.inc"\n')
    return "".join(out)


def output_path(out: Path, unit: nwunits.Unit) -> Path:
    suffix = ".stubs.inc" if unit.kind == "wrapper" else ".stubs.c"
    return out / (unit.name + suffix)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    nwunits.add_common_args(parser)
    parser.add_argument("--out", type=Path, default=nwunits.REPO / "build" / "gen")
    parser.add_argument("--check", action="store_true", help="validate only, write nothing")
    parser.add_argument("--list", action="store_true", help="print every stub")
    args = parser.parse_args()
    args.decomp = nwunits.decomp_tree(args.decomp)

    model = nwunits.load(args.decomp, args.units, args.port_src, args.editor)
    if not nwunits.report(model, sys.stderr):
        return 1
    built = [u for u in model.units if u.kind != "none"]
    if args.list_outputs:
        nwunits.print_outputs(args.out, (output_path(args.out, u) for u in built))
        return 0
    stubs = [f for f in model.functions() if f.provider == "stub"]
    if args.list:
        for f in stubs:
            print(f"{f.unit.name:32} 0x{f.address:08x} {f.host:40} {_origin(f)}")
    written = 0
    if not args.check:
        for unit in built:
            written += nwunits.write_if_changed(output_path(args.out, unit), render(unit))
    by_origin = {
        "visible": sum(1 for f in stubs if not f.erased and not f.include
                       and not f.origin.startswith(("unresolved", "no declaration"))),
        "header": sum(1 for f in stubs if f.include),
        "erased": sum(1 for f in stubs if f.erased),
        "no declaration": sum(1 for f in stubs if f.origin == "no declaration"),
        "unresolved": sum(1 for f in stubs if f.origin.startswith("unresolved")),
    }
    print(f"{len(built)} units built, {len(stubs)} stubs ("
          + ", ".join(f"{v} {k}" for k, v in by_origin.items()) + ")"
          + ("" if args.check else f"; {written} files written to {args.out}"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
