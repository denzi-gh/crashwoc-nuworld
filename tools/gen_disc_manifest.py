#!/usr/bin/env python3
"""Generate src/vfs/disc_manifest.inc: path, size and SHA-256 of every file on the PAL v1.03 disc.

A manifest.json is {"PATH": {"sha256": hex, "size": n}}; --check without SOURCE only validates the committed file.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
INC = REPO / "src" / "vfs" / "disc_manifest.inc"

FILE_COUNT = 451
SKIP = {"DUMMY.DAT"}  # zero padding the game never opens
# Disc identity; the ELF hash is decomp config/pal103/version.json.
KNOWN = {
    "SYSTEM.CNF": (56, "86fe327e4576516f57004800b2663c75c8a65a62872f3fdf3aa0618daf23d9c1"),
    "SLES_503.86": (6731763, "7fc6826d08c42a5a92fc018edae3e520783beb5a8330410251192bfe26b1eca1"),
}

HEADER = "/* Generated by tools/gen_disc_manifest.py from a PAL v1.03 disc; do not edit. */\n"
ROW = re.compile(r'    \{ "([^"\\]+)", (\d+)u, "([0-9a-f]{64})", (0|NW_MANIFEST_SKIP) \},')
PATH = re.compile(r"[A-Z0-9_.\-]+(/[A-Z0-9_.\-]+)*")
SHA = re.compile(r"[0-9a-f]{64}")

Manifest = dict[str, tuple[int, str]]


def from_dir(root: Path) -> Manifest:
    out = {}
    for p in sorted(root.rglob("*")):
        if not p.is_file():
            continue
        h = hashlib.sha256()
        with open(p, "rb") as f:
            while chunk := f.read(1 << 20):
                h.update(chunk)
        out[p.relative_to(root).as_posix().upper()] = (p.stat().st_size, h.hexdigest())
    return out


def from_json(path: Path) -> Manifest:
    data = json.loads(path.read_text(encoding="utf-8"))
    return {k: (int(v["size"]), v["sha256"].lower()) for k, v in data.items()}


def load(source: Path) -> Manifest:
    return from_dir(source) if source.is_dir() else from_json(source)


def render(m: Manifest) -> str:
    rows = [f'    {{ "{path}", {size}u, "{sha}", {"NW_MANIFEST_SKIP" if path in SKIP else 0} }},\n'
            for path, (size, sha) in sorted(m.items())]
    return HEADER + "".join(rows)


def parse_inc(text: str) -> Manifest:
    lines = text.splitlines()
    if not lines or lines[0] + "\n" != HEADER:
        raise ValueError("missing generator header")
    out = {}
    for n, line in enumerate(lines[1:], 2):
        match = ROW.fullmatch(line)
        if not match:
            raise ValueError(f"line {n}: not a manifest row")
        path, size, sha, flags = match.groups()
        if (flags != "0") != (path in SKIP):
            raise ValueError(f"line {n}: {path} has the wrong flags")
        out[path] = (int(size), sha)
    return out


def validate(m: Manifest) -> list[str]:
    errors = []
    if len(m) != FILE_COUNT:
        errors.append(f"{len(m)} files, expected {FILE_COUNT}")
    for path, (size, sha) in sorted(m.items()):
        if not PATH.fullmatch(path):
            errors.append(f"{path}: not an uppercase '/'-separated disc path")
        if size < 0 or not SHA.fullmatch(sha):
            errors.append(f"{path}: bad size or hash")
    for path, want in sorted(KNOWN.items()):
        if m.get(path) != want:
            errors.append(f"{path}: {m.get(path)} is not PAL v1.03 {want}")
    for path in sorted(SKIP - m.keys()):
        errors.append(f"{path}: missing")
    return errors


def compare(a: Manifest, b: Manifest, label: str) -> list[str]:
    errors = [f"{label}: {p} missing" for p in sorted(a.keys() - b.keys())]
    errors += [f"{label}: {p} extra" for p in sorted(b.keys() - a.keys())]
    errors += [f"{label}: {p} {a[p]} != {b[p]}" for p in sorted(a.keys() & b.keys()) if a[p] != b[p]]
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path, nargs="?", help="extracted disc directory or manifest.json")
    parser.add_argument("--cross", type=Path, action="append", default=[], help="manifest.json to agree with")
    parser.add_argument("--out", type=Path, default=INC)
    parser.add_argument("--check", action="store_true", help="compare with the committed file, write nothing")
    args = parser.parse_args()
    if args.source is None and not args.check:
        parser.error("SOURCE is required unless --check")

    errors = []
    committed = None
    if args.check:
        try:
            committed = parse_inc(args.out.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            errors.append(f"{args.out}: {e}")
    m = load(args.source) if args.source else committed
    if m is not None:
        errors += validate(m)
        for path in args.cross:
            errors += compare(m, from_json(path), str(path))
        if committed is not None and args.source:
            errors += compare(m, committed, str(args.out))
    for e in errors:
        print(e, file=sys.stderr)
    if errors:
        return 1
    if not args.check:
        args.out.write_text(render(m), encoding="utf-8", newline="\n")
    print(f"{len(m)} files ({len(SKIP)} skipped)" + (", agree" if args.cross else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
