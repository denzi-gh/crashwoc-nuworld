#!/usr/bin/env python3
"""Generate the function map: retail PS2 address -> host function.

<unit>.funcmap.inc is included at the end of the unit's TU so it can reach statics; funcmap.c is the unit index.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import nwunits  # noqa: E402


def render_unit(unit: nwunits.Unit) -> str:
    rows = [f'    {{ 0x{f.address:08x}u, NW_PROV_{f.provenance.upper()}, "{f.name}", '
            f"(NwFuncPtr){f.host} }},\n" for f in unit.functions]
    return (f"/* Generated by tools/gen_funcmap.py for decomp unit {unit.name}; do not edit. */\n"
            '#include "port/funcmap.h"\n\n'
            "static const NwFuncmapEntry nw_funcmap_entries_[] = {\n"
            + "".join(rows) +
            "};\n\n"
            f"const NwFuncmapUnit {unit.symbol} = {{\n"
            f'    "{unit.name}", nw_funcmap_entries_, {len(unit.functions)}u\n'
            "};\n")


def render_index(units: list[nwunits.Unit]) -> str:
    return ("/* Generated by tools/gen_funcmap.py; do not edit. */\n"
            '#include "port/funcmap.h"\n\n'
            + "".join(f"extern const NwFuncmapUnit {u.symbol};\n" for u in units)
            + "\n/* Address order. */\n"
            "const NwFuncmapUnit *const nw_funcmap_units[] = {\n"
            + "".join(f"    &{u.symbol},\n" for u in units)
            + "};\n\n"
            f"const unsigned nw_funcmap_unit_count = {len(units)}u;\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    nwunits.add_common_args(parser)
    parser.add_argument("--out", type=Path, default=nwunits.REPO / "build" / "gen")
    parser.add_argument("--check", action="store_true", help="validate only, write nothing")
    args = parser.parse_args()
    args.decomp = nwunits.decomp_tree(args.decomp)

    model = nwunits.load(args.decomp, args.units, args.port_src, args.editor)
    built = [u for u in model.units if u.kind != "none"]
    symbols = Counter(u.symbol for u in built)
    for symbol, n in symbols.items():
        if n > 1:
            model.errors.append(f"unit symbol {symbol} is not unique")
    if not nwunits.report(model, sys.stderr):
        return 1
    if args.list_outputs:
        nwunits.print_outputs(args.out, [*(args.out / (u.name + ".funcmap.inc") for u in built),
                                         args.out / "funcmap.c"])
        return 0
    written = 0
    if not args.check:
        for unit in built:
            written += nwunits.write_if_changed(args.out / (unit.name + ".funcmap.inc"),
                                                render_unit(unit))
        written += nwunits.write_if_changed(args.out / "funcmap.c", render_index(built))
    counts = Counter(f.provenance for u in built for f in u.functions)
    print(f"{sum(counts.values())} functions in {len(built)} units ("
          + ", ".join(f"{counts[p]} {p}" for p in nwunits.PROVENANCES) + ")"
          + ("" if args.check else f"; {written} files written to {args.out}"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
