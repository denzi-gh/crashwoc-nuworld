#!/usr/bin/env python3
"""Who owns each retail function on the host: the map for the engine rewrite.

retail   the decomp's C as it is
patched  the decomp's C changed by port patches or value rules (named: the concern, or values/<file>)
copy     NuWorld's definition in place of the decomp's (port/units.toml override)
wrap     NuWorld's definition in front of the decomp's (port/units.toml wrap)
port     NuWorld's definition of a function the decomp has no C for
stub     an aborting stub: no definition yet, or a dead or editor unit
shim     a unit the port replaces as a whole (sdk)

copy, wrap and port are the game layer when NuWorld's definition is under src/gameplay/, else the port layer.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import nwunits  # noqa: E402
import patches  # noqa: E402

KINDS = ("retail", "patched", "copy", "wrap", "port", "stub", "shim")


def touched(pristine: Path, series: Path, values: Path = patches.VALUES) -> dict[tuple[str, str], list[str]]:
    """{(source, function): the concerns and value files that change its body}, in the order they apply."""
    concerns, _ = patches.load_series(series)
    tree = patches.worktree_files(pristine)
    out: dict[tuple[str, str], list[str]] = defaultdict(list)

    def step(name: str, path: str, after: bytes) -> None:
        old, new = nwunits.body_hashes(tree[path], path), nwunits.body_hashes(after, path)
        tree[path] = after
        for fn in sorted(old.keys() | new.keys()):
            if old.get(fn) != new.get(fn):
                out[(path, fn)].append(name)

    for c in concerns:
        for p in c.patches:
            step(c.name, p.path, patches.apply_patch(p, tree[p.path]))
    for rules in patches.load_values(values):
        for path in rules.sites:
            step(f"values/{rules.origin.stem}", path, patches.apply_values(rules, path, tree[path]))
    return out


def port_definitions(port_src: Path) -> dict[str, str]:
    """{function: the NuWorld file that defines it}."""
    out = {}
    for p in sorted(port_src.rglob("*.c")):
        rel = p.relative_to(port_src.parent).as_posix()
        for d in nwunits.scan_c(p.read_bytes().decode("latin-1"), rel).decls:
            if d.is_def and not d.static:
                out.setdefault(d.name, rel)
    return out


def report(model: nwunits.Model, changes: dict, defs: dict[str, str]) -> list[dict]:
    rows = []
    for u in model.units:
        for f in u.functions:
            row = {"unit": u.name, "name": f.name, "address": f"0x{f.address:08x}", "treatment": u.treatment}
            if f.provider == "shim":
                row["kind"] = "shim"
            elif f.provider == "stub":
                row["kind"] = "stub"
            elif f.provider == "port":
                row["kind"] = "wrap" if f.wrapped else "copy" if f.definition is not None else "port"
                row["where"] = defs.get(f.host, "")
                row["layer"] = "game" if row["where"].startswith("src/gameplay/") else "port"
            else:
                concerns = changes.get((u.source, f.name), [])
                row["kind"] = "patched" if concerns else "retail"
                if concerns:
                    row["concerns"] = concerns
            rows.append(row)
    return rows


def render_md(rows: list[dict]) -> str:
    kinds = Counter(r["kind"] for r in rows)
    layers = Counter((r["kind"], r["layer"]) for r in rows if "layer" in r)
    concerns = Counter(c for r in rows for c in r.get("concerns", ()))
    out = ["# Ownership of the retail functions on the host", "",
           "Generated by tools/ownership.py; see its docstring for the kinds.", "",
           "| kind | functions | port layer | game layer |", "|---|---|---|---|"]
    for k in KINDS:
        port, game = layers[(k, "port")], layers[(k, "game")]
        out.append(f"| {k} | {kinds[k]} | {port if k in ('copy', 'wrap', 'port') else ''} | "
                   f"{game if k in ('copy', 'wrap', 'port') else ''} |")
    out += [f"| all | {len(rows)} | | |", "", "| concern | patched functions |", "|---|---|"]
    out += [f"| {c} | {n} |" for c, n in sorted(concerns.items())]
    game = [r for r in rows if r.get("layer") == "game"]
    if game:
        out += ["", "Game layer:", ""] + [f"- {r['unit']}:{r['name']} ({r['kind']}, {r['where']})" for r in game]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    nwunits.add_common_args(parser)
    parser.add_argument("--out", type=Path, default=nwunits.REPO / "build" / "gen")
    parser.add_argument("--patches", type=Path, default=patches.PATCHES, help="the series (default: port/patches)")
    args = parser.parse_args()
    pristine = patches.PRISTINE if args.decomp is None else args.decomp
    decomp = nwunits.decomp_tree(args.decomp)
    model = nwunits.load(decomp, args.units, args.port_src, args.editor)
    if not nwunits.report(model, sys.stderr):
        return 1
    try:
        changes = touched(pristine, args.patches) if args.decomp is None else {}
    except patches.PatchError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    rows = report(model, changes, port_definitions(args.port_src))
    args.out.mkdir(parents=True, exist_ok=True)
    nwunits.write_if_changed(args.out / "ownership.json", json.dumps(rows, indent=1) + "\n")
    nwunits.write_if_changed(args.out / "ownership.md", render_md(rows))
    kinds = Counter(r["kind"] for r in rows)
    print(", ".join(f"{kinds[k]} {k}" for k in KINDS) + f"; {args.out / 'ownership.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
